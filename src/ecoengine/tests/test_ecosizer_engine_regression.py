def _engine(case: str, extra: dict) -> EcosizerEngine:
    """Build an engine; ``case`` is a schematic name with an optional ``|variant`` suffix."""
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return EcosizerEngine(schematic=case.split("|")[0], **_COMMON, **extra)


def _design_capacity(wh) -> float:
    return wh.get_capacity_kbtuh(_DESIGN_OAT_F, _STORAGE_T_F, _DESIGN_INLET_F)


