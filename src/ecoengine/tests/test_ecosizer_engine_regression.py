def _check_sub_system(system, tank_attr, heater_attr, expected):
    tank   = getattr(system, tank_attr, None)
    heater = getattr(system, heater_attr, None)
    if expected is None:
        assert tank is None and heater is None
        return
    exp_vol, exp_cap = expected
    if exp_vol is None:
        assert tank is None
    else:
        assert tank.total_volume_gal == pytest.approx(exp_vol, rel=_REL)
    assert _design_capacity(heater) == pytest.approx(exp_cap, rel=_REL)


class TestPresizedRegression:
    @pytest.mark.parametrize("case", list(_PRESIZED_CASES))
    def test_presized_build_and_sim(self, case):
        extra, exp = _PRESIZED_CASES[case]
        engine = _engine(case, extra)
        system = engine._dhw_system

        # --- construction ---
        assert type(system).__name__ == exp["cls"]
        tank = system.storage_tank
        if exp["tank"] is None:
            assert tank is None
        else:
            cls_name, vol, slope, drawdown = exp["tank"]
            assert type(tank).__name__ == cls_name
            assert tank.total_volume_gal == pytest.approx(vol, rel=_REL)
            assert tank.strat_slope == pytest.approx(slope, rel=_REL)
            assert getattr(tank, "drawdown_fract", None) == drawdown
        caps = [_design_capacity(wh) for wh in system.water_heaters]
        assert caps == pytest.approx(exp["heaters"], rel=_REL)
        _check_sub_system(system, "tm_storage_tank", "tm_water_heater", exp["tm"])
        _check_sub_system(system, "gas_storage_tank", "gas_water_heater", exp["gas"])

        # --- 3-day simulation ---
        run     = engine.simulate_3day()
        summary = engine.get_simulation_summary(run)
        energy, peak, ok, outage, out_sum, tm_sum, min_usable = exp["sim"]
        assert summary["total_energy_kwh"] == pytest.approx(energy, rel=_REL, abs=1e-9)
        assert summary["peak_demand_kw"]   == pytest.approx(peak, rel=_REL, abs=1e-9)
        assert summary["successful"]       is ok
        assert summary["total_outage_min"] == outage
        assert sum(run.heater_output_kbtuh) == pytest.approx(out_sum, rel=_REL)
        assert sum(v or 0.0 for v in run.tm_heater_output_kbtuh) == pytest.approx(tm_sum, rel=_REL, abs=1e-9)
        assert min(run.usable_volume_supplyT_gal) == pytest.approx(min_usable, rel=_REL, abs=1e-9)
        # TM / gas power must be recorded every step so it lines up with primary power
        assert len(run.tm_heater_input_kw) in (0, len(run.heater_power_in_kw))


