class TestClimateRegression:
    @pytest.mark.parametrize("czv,oat,inlet,daily_gal", _CLIMATE_CASES)
    def test_building_resolution(self, czv, oat, inlet, daily_gal):
        engine = EcosizerEngine(
            schematic="primary_no_recirc", **{**_COMMON, "zip_code_or_climate_zone": czv}
        )
        b = engine._building
        assert b.get_design_oat_f()             == pytest.approx(oat, rel=_REL)
        assert b.get_design_inlet_water_temp_f() == pytest.approx(inlet, rel=_REL)
        assert b.daily_dhw_use_supplyT_gal      == pytest.approx(daily_gal, rel=_REL)


